"""
Extract OpenMC shield-sweep results and compute normalized NRT metrics.

This script assumes statepoint files have been generated by run_sweep.py.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import openmc
import pandas as pd

from model import (
    SI_DISPLACEMENT_THRESHOLD_EV,
    dpa_per_fluence,
    nrt_displacements_per_source,
)


ROOT = Path(__file__).resolve().parent
RUNS_DIR = ROOT / "runs"
RESULTS_DIR = ROOT / "results"

REFERENCE_FLUENCE_N_CM2 = 1.0e15


def find_statepoint(case_dir: Path) -> Path | None:
    files = sorted(case_dir.glob("statepoint.*.h5"))
    return files[-1] if files else None


def main():
    manifest_path = RUNS_DIR / "run_manifest.json"

    if not manifest_path.exists():
        raise SystemExit(
            "No run manifest found. Run run_sweep.py first."
        )

    manifest = json.loads(
        manifest_path.read_text(encoding="utf-8")
    )

    rows = []

    for case in manifest:
        case_dir = RUNS_DIR / case["case"]
        statepoint_path = find_statepoint(case_dir)

        if statepoint_path is None:
            continue

        with openmc.StatePoint(statepoint_path) as sp:
            damage_tally = sp.get_tally(
                name="silicon_damage_energy"
            )
            flux_tally = sp.get_tally(
                name="silicon_flux"
            )

            damage_mean = float(
                damage_tally.mean.ravel()[0]
            )
            damage_std = float(
                damage_tally.std_dev.ravel()[0]
            )

            flux_mean = float(
                flux_tally.mean.ravel()[0]
            )
            flux_std = float(
                flux_tally.std_dev.ravel()[0]
            )

        nrt_displacements = nrt_displacements_per_source(
            damage_mean
        )

        dpa_1e15 = dpa_per_fluence(
            nrt_displacements,
            REFERENCE_FLUENCE_N_CM2,
        )

        rows.append(
            {
                **case,
                "damage_energy_eV_per_source": damage_mean,
                "damage_energy_std_eV_per_source": damage_std,
                "silicon_flux_per_source": flux_mean,
                "silicon_flux_std_per_source": flux_std,
                "si_displacement_threshold_eV": SI_DISPLACEMENT_THRESHOLD_EV,
                "nrt_displacements_per_source": nrt_displacements,
                "nrt_dpa_per_1e15_n_cm2": dpa_1e15,
            }
        )

    if not rows:
        raise SystemExit(
            "No completed OpenMC statepoint files were found."
        )

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)

    output = pd.DataFrame(rows)

    output.to_csv(
        RESULTS_DIR / "openmc_matched_energy_results.csv",
        index=False,
    )

    print(output.to_string(index=False))


if __name__ == "__main__":
    main()
